import UserModel from "../models/userModel.js";
import jwt from "jsonwebtoken";
import bcrypt from "bcryptjs";

async function registerUser(req, res) {
  try {
    const { username, email, password, role = "user" } = req.body || {};

    if (!username || !email || !password || !role) {
      return res.status(400).json({ message: "All fields are required" });
    }
    // does not allow same user to be registered with same username and email
    const isUserAlreadyRegistered = await UserModel.findOne({
      $or: [{ username: username }, { email: email }],
    });
    // password hashing and salt generation using bcryptjs method
    // salt is random string generated by bcryptjs for each password
    // and 10 is salt rounds which can be increased for more security
    // but it will take more time to hash and unhash
    const hashedPassword = await bcrypt.hash(password, 10);
    if (isUserAlreadyRegistered) {
      return res.status(400).json({ message: "User already registered" });
    }
    // create user
    const user = await UserModel.create({
      username,
      email,
      password: hashedPassword,
      role,
    });
    // jwt token for user
    const token = jwt.sign(
      { id: user._id, role: user.role },
      process.env.JWT_SECRET,
    );
    // set http only cookie for user
    res.cookie("token", token);

    res.status(201).json({
      message: "User registered successfully",
      user: {
        id: user._id,
        username: user.username,
        email: user.email,
        role: user.role,
      },
    });
  } catch (error) {
    console.error("Error in user registration:", error);
    res.status(500).json({ message: "Internal server error" });
  }
}

async function loginUser(req, res) {
  try {
    const { username, email, password } = req.body || {};
    if ((!username && !email) || !password) {
      return res.status(400).json({ message: "All fields are required" });
    }


    const user = await UserModel.findOne({
      $or: [
        ...(username ? [{ username }] : []),
        ...(email ? [{ email }] : [])
      ]
    });
    if (!user) {
      return res.status(401).json({ message: "Invalid credentials" });
    }
    const isPasswordValid = await bcrypt.compare(password, user.password);
    // bcrypt.compare() compares the plain text password with the hashed password and return true or false
    // this first turn password into hash and then compare it with the stored hashed password
    // no extra 
    if (!isPasswordValid) {
      return res.status(401).json({ message: "Invalid credentials" });
    }
    const token = jwt.sign(
      { id: user._id, role: user.role },
      process.env.JWT_SECRET,
    );
    res.cookie("token", token);
    res.status(200).json({
      message: "Login successful",
      user: {
        id: user._id,
        username: user.username,
        email: user.email,
        role: user.role,
      },
    });
  } catch (error) {
    console.error("Error in user login:", error);
    res.status(500).json({ message: "Internal server error" });
  }
}

export { registerUser, loginUser };
